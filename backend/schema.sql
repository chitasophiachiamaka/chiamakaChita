CREATE TABLE IF NOT EXISTS students (
    id TEXT PRIMARY KEY,
    display_name TEXT NOT NULL,
    class_name TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS results (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id TEXT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    subject TEXT NOT NULL,
    score SMALLINT NOT NULL CHECK (score BETWEEN 0 AND 100),
    term TEXT NOT NULL CHECK (term IN ('First term', 'Second term', 'Third term')),
    UNIQUE (student_id, subject, term)
);

CREATE INDEX IF NOT EXISTS results_term_idx ON results(term);
CREATE INDEX IF NOT EXISTS students_class_idx ON students(class_name);
